#!/usr/bin/env bash
# Orla container entrypoint (runs as root under tini, then drops to `orla`).
#
#  1. Prepare writable directories on the volumes.
#  2. Probe the Nginx build and the kernel, write runtime listen includes and
#     capabilities.json for the template engine.
#  3. Apply database migrations.
#  4. Validate the Nginx config; quarantine generated host files if the
#     persisted config is invalid (the panel recompiles them from the DB).
#  5. Run Nginx in the foreground and keep the panel process alive. If Nginx
#     exits the container exits, so Docker's restart policy takes over. A crash
#     of the panel never takes Nginx down: it is restarted in place.
set -Eeuo pipefail

readonly ORLA_USER="orla"
readonly APP_DIR="/opt/orla"
readonly APP_ENTRY="${ORLA_APP_ENTRY:-${APP_DIR}/dist/server/index.js}"
readonly RUNTIME_DIR="/etc/nginx/orla/runtime"
readonly GENERATED_DIR="/etc/nginx/orla/generated"
readonly HOSTS_DIR="/etc/nginx/conf.d"
readonly DATA_DIR="/var/lib/orla"
readonly LOG_DIR="/var/log/orla"
readonly CACHE_DIR="/var/cache/orla/nginx"
readonly PID_DIR="/run/orla"
# Passed to every nginx invocation so the compiled-in default error log
# (/var/log/nginx/error.log) is never opened by the unprivileged master.
readonly NGINX_ERROR_LOG="${LOG_DIR}/nginx/error.log"

log() {
    printf '%s [entrypoint] %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"
}

as_orla() {
    gosu "${ORLA_USER}" "$@"
}

prepare_directories() {
    install -d -o "${ORLA_USER}" -g "${ORLA_USER}" -m 0750 \
        "${DATA_DIR}" "${DATA_DIR}/data" "${DATA_DIR}/snapshots" "${DATA_DIR}/quarantine" \
        "${HOSTS_DIR}" \
        "${GENERATED_DIR}" "${GENERATED_DIR}/http.d" "${GENERATED_DIR}/ip-lists" \
        "${GENERATED_DIR}/htpasswd" "${GENERATED_DIR}/certs" "${GENERATED_DIR}/www" \
        "${LOG_DIR}" "${LOG_DIR}/nginx" \
        "${CACHE_DIR}" "${CACHE_DIR}/proxy" "${CACHE_DIR}/temp" \
        "${CACHE_DIR}/temp/client_body" "${CACHE_DIR}/temp/proxy" "${CACHE_DIR}/temp/fastcgi" \
        "${CACHE_DIR}/temp/uwsgi" "${CACHE_DIR}/temp/scgi" \
        "${PID_DIR}"
    # The ACME webroot must be readable by Nginx workers and writable by the panel.
    install -d -o "${ORLA_USER}" -g "${ORLA_USER}" -m 0755 "${DATA_DIR}/acme"
    install -d -o root -g "${ORLA_USER}" -m 0750 "${RUNTIME_DIR}"
}

ensure_fallback_certificate() {
    if [[ ! -s "${RUNTIME_DIR}/fallback.crt" || ! -s "${RUNTIME_DIR}/fallback.key" ]]; then
        log "generating self-signed fallback certificate"
        openssl req -x509 -nodes -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 \
            -days 3650 -subj "/CN=orla-fallback" \
            -keyout "${RUNTIME_DIR}/fallback.key" -out "${RUNTIME_DIR}/fallback.crt" >/dev/null 2>&1
    fi
    chown root:"${ORLA_USER}" "${RUNTIME_DIR}/fallback.key" "${RUNTIME_DIR}/fallback.crt"
    chmod 0640 "${RUNTIME_DIR}/fallback.key"
    chmod 0644 "${RUNTIME_DIR}/fallback.crt"
}

json_bool() {
    if "$@"; then printf 'true'; else printf 'false'; fi
}

module_enabled() {
    compgen -G "/etc/nginx/modules-enabled/*$1*" >/dev/null
}

probe_capabilities() {
    local nginx_build nginx_version http3 ipv6 brotli headers_more
    nginx_build="$(nginx -V 2>&1)"
    nginx_version="$(nginx -v 2>&1 | sed -n 's|.*nginx/\([0-9.]*\).*|\1|p')"

    http3="$(json_bool grep -q -- '--with-http_v3_module' <<<"${nginx_build}")"
    if [[ "${ORLA_DISABLE_HTTP3:-false}" == "true" ]]; then
        http3="false"
    fi

    if [[ "${ORLA_IPV6:-auto}" == "auto" ]]; then
        ipv6="$(json_bool test -s /proc/net/if_inet6)"
    elif [[ "${ORLA_IPV6}" == "true" ]]; then
        ipv6="true"
    else
        ipv6="false"
    fi

    brotli="$(json_bool module_enabled brotli)"
    headers_more="$(json_bool module_enabled headers-more)"

    {
        echo "# Generated by the entrypoint on every start."
        echo "listen 80 default_server;"
        if [[ "${ipv6}" == "true" ]]; then
            echo "listen [::]:80 default_server;"
        fi
    } >"${RUNTIME_DIR}/listen-default-http.conf"

    {
        echo "# Generated by the entrypoint on every start."
        echo "listen 443 ssl default_server;"
        if [[ "${ipv6}" == "true" ]]; then
            echo "listen [::]:443 ssl default_server;"
        fi
        if [[ "${http3}" == "true" ]]; then
            echo "listen 443 quic reuseport default_server;"
            if [[ "${ipv6}" == "true" ]]; then
                echo "listen [::]:443 quic reuseport default_server;"
            fi
        fi
    } >"${RUNTIME_DIR}/listen-default-https.conf"

    cat >"${RUNTIME_DIR}/capabilities.json" <<JSON
{
  "nginxVersion": "${nginx_version}",
  "http3": ${http3},
  "ipv6": ${ipv6},
  "brotli": ${brotli},
  "headersMore": ${headers_more}
}
JSON
    chown root:"${ORLA_USER}" "${RUNTIME_DIR}"/*.conf "${RUNTIME_DIR}/capabilities.json"
    chmod 0644 "${RUNTIME_DIR}"/*.conf "${RUNTIME_DIR}/capabilities.json"
    log "nginx ${nginx_version}: http3=${http3} ipv6=${ipv6} brotli=${brotli} headers_more=${headers_more}"
}

migrate_database() {
    log "applying database migrations"
    (cd "${APP_DIR}" && as_orla ./node_modules/.bin/prisma migrate deploy)
}

validate_nginx() {
    local output
    if output="$(as_orla nginx -e "${NGINX_ERROR_LOG}" -t 2>&1)"; then
        return 0
    fi
    log "persisted configuration is invalid:"
    printf '%s\n' "${output}"

    local target
    target="${DATA_DIR}/quarantine/$(date -u +%Y%m%dT%H%M%SZ)"
    log "moving generated files to ${target}; the panel recompiles them from the database"
    as_orla mkdir -p "${target}/conf.d" "${target}/http.d"
    find "${HOSTS_DIR}" -maxdepth 1 -name 'host-*.conf' -exec mv -t "${target}/conf.d" {} +
    find "${GENERATED_DIR}/http.d" -maxdepth 1 -name '*.conf' -exec mv -t "${target}/http.d" {} +

    as_orla nginx -e "${NGINX_ERROR_LOG}" -t
}

NGINX_PID=""
APP_LOOP_PID=""

shutdown() {
    log "stopping"
    if [[ -n "${APP_LOOP_PID}" ]]; then
        kill -TERM "${APP_LOOP_PID}" 2>/dev/null || true
    fi
    if [[ -n "${NGINX_PID}" ]]; then
        kill -QUIT "${NGINX_PID}" 2>/dev/null || true
        wait "${NGINX_PID}" 2>/dev/null || true
    fi
    exit 0
}

run_app_forever() {
    local child=""
    trap 'if [[ -n "${child}" ]]; then kill -TERM "${child}" 2>/dev/null; wait "${child}"; fi; exit 0' TERM INT
    while true; do
        as_orla node "${APP_ENTRY}" &
        child=$!
        wait "${child}" || true
        child=""
        log "panel process exited; restarting in 2s"
        sleep 2
    done
}

main() {
    prepare_directories
    ensure_fallback_certificate
    probe_capabilities
    migrate_database
    validate_nginx

    trap shutdown TERM INT

    log "starting nginx"
    as_orla nginx -e "${NGINX_ERROR_LOG}" -g 'daemon off;' &
    NGINX_PID=$!

    log "starting panel"
    run_app_forever &
    APP_LOOP_PID=$!

    local status=0
    wait "${NGINX_PID}" || status=$?
    log "nginx exited with status ${status}"
    kill -TERM "${APP_LOOP_PID}" 2>/dev/null || true
    wait "${APP_LOOP_PID}" 2>/dev/null || true
    exit "${status:-1}"
}

if [[ "$#" -gt 0 ]]; then
    exec "$@"
fi

main
